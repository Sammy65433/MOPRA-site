export function startingLanguage() {
  try {
    const saved = localStorage.getItem("mopra-language");
    if (saved && translations[saved]) return saved;
  } catch {
    // Language selection still works without local storage.
  }

  const browser =
    typeof navigator === "undefined" ? "en" : navigator.language.toLowerCase();

  if (browser.startsWith("fr")) return "fr";
  if (browser.startsWith("ht")) return "ht";
  return "en";
}
